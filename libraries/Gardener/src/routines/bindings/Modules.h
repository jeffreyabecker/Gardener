#pragma once

#include <any>
#include <memory>
#include <vector>

#include <berry.h>

#include "panel/page/SettingsScene.h"

namespace gardener {

namespace panel::page {
class SettingsRow;
}  // namespace panel::page

namespace berry {

class BindingContext;

// The six native modules a routine sees, installed into a fresh VM by the interpreter:
//
//   vacuum.*    the machine, read and commanded
//   screen.*    the drawing a page describes: a node per call, aggregated into records the panel
//               can draw later
//   device.*    the device: the target it stores, the piezo, the clock, the log and the presses
//               waiting for a page
//   settings.*  the declaration of a setting: a class per kind, each call holding the row it built
//   routines.*  the registry: register() a record with the class its page is built from, activate()
//               the page a launch builds, and the set it reads and writes
//   ux.*        the stack: push() a page over the one showing, pop() it, pop_to_root() to the root
//
// Each is installed from its own file in this folder: the module's callbacks and its table are
// file-local, and only the installer is exported.
//
// A routine file declares its settings with the settings module's kinds and hands them, with the
// page class, to `routines.register`; every declaration is consumed into the record.
//
// A page describes its drawing rather than making it: every `screen` call answers a `draw` record,
// which is a node of the tree the panel is handed. Some of the other answers a routine reads are
// records too — the ink box `screen.measure` answers, a row the browser lists, and the value a
// launched page's init is given, a `RoutineActivation`. Each module declares its own, in the
// `bnfuncinfo` table it installs: an entry with no function is an instance variable, so the fields a
// page reads sit beside the code that fills them. The settings a routine declares are not records:
// they are objects the `settings` module's classes build, and each holds the row it was declared
// with.
//
// The reference a routine author reads is the tables in this folder: what a routine can call and
// what it must be, as the same surface in code. One file there is one of the modules, and this
// header is only the declarations.
//
// They are built at runtime rather than declared in the interpreter's module table: that table is
// generated by upstream's code generator (`tools/coc`), and this build does not run it.
//
// One VM and one app, so the native callbacks -- plain C functions with no user data -- reach their
// owners through the BindingContext the interpreter holds.
void installVacuumModule(bvm* vm, BindingContext& bindings);
void installScreenModule(bvm* vm, BindingContext& bindings);
void installDeviceModule(bvm* vm, BindingContext& bindings);
// The stack a page moves through, from Berry: push() a page over the one showing, pop() the top one
// and pop_to_root() every page above the root. Installs the record a native factory carries a scene
// back to the image in.
void installUxModule(bvm* vm, BindingContext& bindings);
// The settings module's declarations, the rows a settings list declares, each one consumed: a row
// belongs to the one record that takes it. Installs the record a declaration is read back through,
// and the SettingsEditScene the image opens a declaration list with.
void installSettingsModule(bvm* vm, BindingContext& bindings);
// The rows a settings list declares, in order, each declaration consumed: a row belongs to the one
// record that takes it. Raises, leaving every declaration as it was, for a list holding anything
// else.
std::vector<std::unique_ptr<panel::page::SettingsRow>> takeSettingsRows(bvm* vm, int index);
// The declaration a row was built from, as the record a page reads it back through: the row, held by
// pointer, with the key, label, kind and the step, bounds and entries that kind was declared with.
// Left on the stack for the caller to push onto a list.
void pushSettingDeclaration(bvm* vm, panel::page::SettingsRow* row);
// One value in the type a setting holds it in: nil for nothing, a flag, a whole number, a real or a
// key. What a scene answers when it pops is read the same way.
void pushSettingValue(bvm* vm, const std::any& value);
// A set as a map the image reads: one entry per key, in the order the map answered them.
void pushSettingsMap(bvm* vm, const panel::page::SettingValues& values);
// A map as a set: every key that holds a value a setting can hold. False for a value that is not a
// map, which the caller refuses.
bool takeSettingMap(bvm* vm, int index, panel::page::SettingValues& values);
// A scene a native factory built, carried into the image as an instance the one field holds. The
// stack owns the scene once it is pushed; a handle that is never pushed frees it with the
// collector, and one pushed twice has nothing to give the second time.
void pushSceneHandle(bvm* vm, std::unique_ptr<panel::page::Scene> scene);
// The module a routine file registers itself through: register(key, title, icon, settings,
// scene_class) hands the registry a record with the class its page is built from, activate(key,
// values) answers the page a launch builds, load_settings and save_settings read and write the
// routine's set, rows and title answer the browser's list, and settings_cfgs the declarations its
// settings list is built from.
void installRoutinesModule(bvm* vm, BindingContext& bindings);

}  // namespace berry
}  // namespace gardener
