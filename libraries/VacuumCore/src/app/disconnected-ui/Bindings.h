#pragma once

struct bvm;

namespace gardener {

class AppContext;
class Routines;
class StreamLogger;

namespace berry {

// The five native modules a routine sees, installed into a fresh VM:
//
//   vacuum.*   the machine, read and commanded
//   screen.*   the panel, plus the unit it prints
//   buttons.*  the presses since the last call
//   routines.* the registry, so a file can register itself
//   store.*    the routine's own values, kept across a power cycle
//
// The reference a routine author reads is docs/routines.md; the tables below are the same surface
// as code, and the two have to move together.
//
// They are built at runtime rather than declared in the interpreter's module table: that table is
// generated by upstream's code generator (`tools/coc`), and this build does not run it.
//
// One VM and one app, so the native callbacks -- plain C functions with no user data -- reach their
// owners through the pointers given here.
void install(bvm* vm, AppContext& context, Routines& routines, StreamLogger& logger);

}  // namespace berry
}  // namespace gardener
