#!/usr/bin/env python3
"""Writes the default of every GARDENER_KNOB_VALID into the header the compiler reads.

A macro cannot apply a knob's own default: doing so means asking whether the token is already
defined, and a macro expansion cannot contain a preprocessing directive. The default is therefore an
argument of GARDENER_KNOB_VALID, read here, and the #ifndef block that hands it to the compiler is
written out to libraries/Gardener/src/core/knob_defaults.h. Both build entry points run this before
they compile; the generated header is committed so a checkout and an editor see the tokens too.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "libraries" / "Gardener" / "src" / "core" / "knob_defaults.h"
SCANNED = ("libraries/Gardener/src", "libraries/Runtime/src", "firmware")
BANNER = (
    "#pragma once\n"
    "// Generated by tools/knob.py from the GARDENER_KNOB_VALID calls. Do not edit.\n"
)
TOKEN = re.compile(r"^GARDENER_[A-Z0-9_]+$")


def stripped(text):
    """The text with comments removed, so a knob in a comment is not a knob and a message's commas
    are never read as separators."""
    out, index, quoted, escaped = [], 0, False, False
    while index < len(text):
        character = text[index]
        if quoted:
            out.append(character)
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == '"':
                quoted = False
            index += 1
        elif character == '"':
            quoted = True
            out.append(character)
            index += 1
        elif text.startswith("//", index):
            index = text.find("\n", index)
            if index == -1:
                break
        elif text.startswith("/*", index):
            end = text.find("*/", index + 2)
            index = len(text) if end == -1 else end + 2
        else:
            out.append(character)
            index += 1
    return "".join(out)


def directives_removed(text):
    """The text without preprocessor lines, so the macro that names a knob is not read as one."""
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))


def arguments(text):
    """The argument list of every GARDENER_KNOB_VALID(...) in text, across line breaks."""
    marker = "GARDENER_KNOB_VALID("
    index = 0
    while (start := text.find(marker, index)) != -1:
        depth, current, parts, quoted, escaped = 0, [], [], False, False
        for position in range(start + len(marker) - 1, len(text)):
            character = text[position]
            if quoted:
                current.append(character)
                if escaped:
                    escaped = False
                elif character == "\\":
                    escaped = True
                elif character == '"':
                    quoted = False
                continue
            if character == '"':
                quoted = True
                current.append(character)
            elif character == "(":
                depth += 1
                if depth > 1:
                    current.append(character)
            elif character == ")" and depth > 0:
                depth -= 1
                if depth == 0:
                    parts.append("".join(current).strip())
                    yield parts
                    index = position + 1
                    break
                current.append(character)
            elif character == "," and depth == 1:
                parts.append("".join(current).strip())
                current = []
            else:
                current.append(character)
        else:
            sys.exit(f"GARDENER_KNOB_VALID at byte {start} is never closed")


def knobs():
    found = {}
    for directory in SCANNED:
        for path in sorted((ROOT / directory).rglob("*")):
            if path.suffix not in (".h", ".cpp"):
                continue
            # The build path holds a copy of the sketch and the staged libraries; a knob there is the
            # same knob twice.
            if "build" in path.relative_to(ROOT).parts:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            for parts in arguments(directives_removed(stripped(text))):
                if len(parts) != 6:
                    sys.exit(f"{path}: GARDENER_KNOB_VALID takes (type, name, token, default, "
                             f"assertion, message), not {len(parts)}")
                name, token, default = parts[1], parts[2], parts[3]
                if not TOKEN.match(token):
                    sys.exit(f"{path}: {name}'s token {token} is not GARDENER_SCREAMING_SNAKE_CASE")
                if token in found:
                    sys.exit(f"{path}: {token} is already declared by {found[token][1]}")
                found[token] = (default, path)
    return found


def main():
    found = knobs()
    OUTPUT.write_text(
        BANNER + "".join(f"#ifndef {token}\n#define {token} {default}\n#endif\n"
                         for token, (default, _) in sorted(found.items())),
        encoding="utf-8", newline="\n")
    print(f"{len(found)} knobs -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
